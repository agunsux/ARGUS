process.env.NODE_ENV = 'test';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
process.env.ARGUS_DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'tikum-editorial-test-'));
const { ArticleRepository, articleRepository } = require('./src/content/ArticleRepository');
const { DurableArticleStore } = require('./src/content/DurableArticleStore');
const { scoreOpportunity, editorialSlots } = require('./src/content/OpportunityResearch');

assert.strictEqual(ArticleRepository.isArticleDue({ status: 'scheduled', scheduled_at: '2020-01-01' }), false);
assert.strictEqual(ArticleRepository.isArticleDue({ status: 'draft' }), false);
assert.strictEqual(ArticleRepository.isArticleDue({ status: 'published', published_at: '2020-01-01' }), true);
const candidate = { type: 'historical' };
assert.strictEqual(scoreOpportunity(candidate).score, null);
assert.strictEqual(scoreOpportunity(candidate).eligible_for_selection, false);
assert.strictEqual(scoreOpportunity(candidate).evidence_coverage_percent, 0);
const factors = Object.fromEntries(['demand', 'momentum', 'intent', 'opportunity', 'inventory', 'conversion'].map(k => [k, { value: 50, source: 'test-fixture', researched_at: '2026-11-07' }]));
assert.strictEqual(scoreOpportunity({ type: 'upcoming', factors }).score, 50);
assert.strictEqual(scoreOpportunity({ type: 'historical', factors }).eligible_for_selection, false);
assert.strictEqual(scoreOpportunity({ type: 'historical', factors, event_occurred_verified: true }).eligible_for_selection, true);
const slots = editorialSlots('2026-11-07T10:00:00+07:00');
assert.strictEqual(slots.length, 8);
assert.strictEqual(slots[0].scheduled_at, '2026-11-10T03:00:00.000Z');
assert.strictEqual(slots[7].scheduled_at, '2026-12-04T03:00:00.000Z');
assert.strictEqual(editorialSlots('2026-11-10T03:00:00Z')[0].scheduled_at, '2026-11-13T03:00:00.000Z');
const data = { title: 'Test editorial safety unique title', description: 'An isolated test description with enough characters for validation.', content: '<h2>Test</h2><p>This isolated fixture tests publication failure rollback without touching any production content or database.</p>', category: 'ticket-guides' };
const article = articleRepository.saveArticle(data);
assert.throws(() => articleRepository.saveArticle(data), /already exists/);
assert.throws(() => articleRepository.scheduleArticle(article.id, 'invalid'), /approved/);
articleRepository.approveArticle(article.id, 'test-editor');
assert.throws(() => articleRepository.scheduleArticle(article.id, 'invalid'), /Invalid time/);
assert.strictEqual(article.status, 'approved');
const originalPersist = DurableArticleStore.persist;
DurableArticleStore.persist = () => { throw new Error('simulated disk failure'); };
assert.throws(() => articleRepository.publishArticle(article.id), /simulated disk failure/);
assert.strictEqual(article.status, 'approved');
assert.strictEqual(article.published_at, null);
assert.throws(() => articleRepository.saveArticle({ ...article, title: 'Unpersisted changed title' }), /simulated disk failure/);
assert.strictEqual(articleRepository.getArticleById(article.id).title, data.title);
DurableArticleStore.persist = originalPersist;
assert.strictEqual(articleRepository.publishArticle(article.id).success, true);
assert.strictEqual(articleRepository.publishArticle(article.id).alreadyPublished, true);
const cron = require('./vercel.json').crons.filter(c => c.path === '/api/content/scheduler/cron');
assert.strictEqual(cron.length, 1);
assert.strictEqual(cron[0].schedule, '0 3 * * 2,5');
console.log('PASS: editorial visibility, evidence scoring, historical eligibility, WIB slots, slug collision, invalid dates, persistence rollback, idempotency and cron configuration');
console.log(`Isolated test artifacts: ${process.env.ARGUS_DATA_DIR}`);
process.exit(0);